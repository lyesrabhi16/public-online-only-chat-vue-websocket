const dictionaries: Record<Locale, Record<string, string>> = { en, fr }

/** French if the browser is set to French, English otherwise. */
export function detectLocale(language: string = typeof navigator === 'undefined' ? 'en' : navigator.language): Locale {
  return language.toLowerCase().startsWith('fr') ? 'fr' : 'en'
}

/** The language in use. It lives in memory only: the page asks the browser again each time it loads. */
export const locale = ref<Locale>(detectLocale())

export function t(key: Key, params: Record<string, string | number> = {}): string {
  const text = dictionaries[locale.value][key] ?? en[key]
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}

/** A refusal from the server shown in the language of the page (the server's own sentence is the fallback). */
export function errorText(refusal: { code?: string; error?: string; params?: Record<string, string | number> }): string {
  const key = `error.${refusal.code}` as Key
  if (refusal.code && key in en) return t(key, refusal.params)
  return refusal.error ?? t('error.no_answer')
}

export function keysOf(l: Locale): string[] {
  return Object.keys(dictionaries[l])
}
